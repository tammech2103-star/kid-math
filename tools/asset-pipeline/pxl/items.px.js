// Every sprite uses shades() for a hue-shifted ramp and selout:"k" so the
// silhouette follows the chapter's deep colour instead of black.
function theme(ink, accent, extra) {
  // Semantic names in the call sites stay readable; pxl palette keys must be
  // exactly one character, so normalise the (single) extra colour to "a".
  const colors = { k: ink, w: "#FFF8E7" };
  Object.values(extra || {}).forEach((value, i) => {
    colors["abcdefghijklmnopqrstuvwxyz"[i]] = value;
  });
  pal(colors);
  shades("1234", accent);
}

// pxl has no built-in polyline: return a canvas-callback that draws each
// consecutive pair as a thick line (function items receive the canvas as c).
function stroke(pts, color, width) {
  return (c) => {
    for (let i = 0; i + 3 < pts.length; i += 2) {
      c.line(pts[i], pts[i + 1], pts[i + 2], pts[i + 3], color, width);
    }
  };
}

